def test_1_gemini_is_the_configured_provider(monkeypatch):
    """Test 1: Gemini is the configured provider."""
    monkeypatch.setenv("LLM_PROVIDER", "gemini")
    monkeypatch.setenv("GEMINI_API_KEY", "test-key")
