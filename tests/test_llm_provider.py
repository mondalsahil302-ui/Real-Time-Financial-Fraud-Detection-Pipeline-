def test_gemini_requires_the_server_side_api_key(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    with pytest.raises(LLMProviderError, match="GEMINI_API_KEY is not configured"):
        GeminiProvider()


def test_gemini_uses_bounded_retries_and_json_chat_config(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-only-key")
    calls = []
    delays = []

    class TemporaryFailure(Exception):
        status_code = 503

    class Models:
        def generate_content(self, **kwargs):
            calls.append(kwargs)
            if len(calls) < 3:
                raise TemporaryFailure()
            return type("Response", (), {"text": '{"answer":"grounded","evidence_ids":[],"uncertainties":[]}'})()

    client = type("Client", (), {"models": Models()})()
    provider = GeminiProvider(client=client, sleep=delays.append)

    response = provider.generate("question", "system")

    assert json.loads(response)["answer"] == "grounded"
    assert len(calls) == 3
    assert delays == [0.5, 1.0]
    assert calls[-1]["model"] == provider.model
    assert calls[-1]["config"].system_instruction == "system"
    assert calls[-1]["config"].response_mime_type == "application/json"


def test_gemini_stops_after_two_retries(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-only-key")
    calls = []
    delays = []

    class TemporaryFailure(Exception):
        status_code = 503

    class Models:
        def generate_content(self, **kwargs):
            calls.append(kwargs)
            raise TemporaryFailure()

    client = type("Client", (), {"models": Models()})()
    provider = GeminiProvider(client=client, sleep=delays.append)

    with pytest.raises(LLMProviderError, match="Gemini endpoint is unavailable"):
        provider.generate("question")

    assert len(calls) == 3
    assert delays == [0.5, 1.0]


